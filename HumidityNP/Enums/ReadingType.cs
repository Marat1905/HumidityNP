namespace HumidityNP.Enums;

/// <summary>
/// Тип измерения (первый байт пакета данных).
/// Определяет формат и интерпретацию последующих байтов.
/// </summary>
/// <remarks>
/// Согласно документации X0 Series BLE Protocol 2.0:
/// - Pin readings (0x02-0x07): измерения влажности с помощью штыревых электродов
/// - RHT reading (0x11): относительная влажность и температура
/// </remarks>
public enum ReadingType : byte
{
    /// <summary>
    /// Нет доступных измерений.
    /// Используется когда счётчик сохранённых показаний равен 0.
    /// </summary>
    NoReading = 0x00,

    /// <summary>
    /// Измерение древесины без изолированных штырей.
    /// Диапазон: 4.3–60.0% MC (moisture content).
    /// Значение: 43-600 в единицах 0.1% MC.
    /// С температурной компенсацией.
    /// </summary>
    NonInsulatedWood = 0x02,

    /// <summary>
    /// Измерение древесины с изолированными штырями.
    /// Диапазон: 6.0–60.0% MC.
    /// Значение: 60-600 в единицах 0.1% MC.
    /// С температурной компенсацией.
    /// </summary>
    InsulatedWood = 0x03,

    /// <summary>
    /// Измерение гипсокартона без изолированных штырей.
    /// Диапазон: 0.1–6.0% MC.
    /// Значение: 1-60 в единицах 0.1% MC.
    /// Без температурной компенсации.
    /// </summary>
    NonInsulatedDrywall = 0x04,

    /// <summary>
    /// Измерение гипсокартона с изолированными штырями.
    /// Диапазон: 0.1–6.0% MC.
    /// Значение: 1-60 в единицах 0.1% MC.
    /// Без температурной компенсации.
    /// </summary>
    InsulatedDrywall = 0x05,

    /// <summary>
    /// Относительное измерение без изолированных штырей.
    /// Диапазон: 0-100 (безразмерные единицы).
    /// Без температурной компенсации.
    /// </summary>
    NonInsulatedRef = 0x06,

    /// <summary>
    /// Относительное измерение с изолированными штырями.
    /// Диапазон: 0-100 (безразмерные единицы).
    /// Без температурной компенсации.
    /// </summary>
    InsulatedRef = 0x07,

    /// <summary>
    /// Измерение относительной влажности и температуры (RHT).
    /// Имеет другую структуру данных (12 байт вместо 6).
    /// </summary>
    RHT = 0x11
}